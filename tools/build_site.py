def ul(text):
    """Italic word(s) with a hand-drawn underline."""
    return (f'<em class="ul">{esc(text)}<svg viewBox="0 0 200 12" preserveAspectRatio="none" aria-hidden="true">'
            '<path d="M3 8c30-5 60-4 95-2s60 2 99-3"/></svg></em>')


def h1(pre, em, post):
    return f"<h1>{esc(pre)} {ul(em)} {esc(post)}</h1>"


def cut(num, label):
    return f'<div class="cut">{SCISSORS}<i>{num:02d}</i> {esc(label)}</div>'


def video(name, cls="", autoplay=True):
    """<video> with whichever of media/<name>.webm / .mp4 exist. Posters are JPEGs of the same name."""
    srcs = ""
    if (ROOT / "media" / f"{name}.webm").exists():
        srcs += f'<source src="/media/{name}.webm" type="video/webm">'
    srcs += f'<source src="/media/{name}.mp4" type="video/mp4">'
    ap = " autoplay" if autoplay else ""
    c = f' class="{cls}"' if cls else ""
    return (f'<video{c} poster="/media/{name}.jpg"{ap} muted loop playsinline preload="metadata">{srcs}</video>')


def polaroid(name, caption):
    return (f'<figure class="pol"><div class="scr">{video(name)}</div>'
            f'<figcaption class="cap">{esc(caption)}</figcaption></figure>')


def polaroids(names, captions, cls="pols", extra=""):
    inner = "".join(polaroid(n, c) for n, c in zip(names, captions))
    return f'<div class="{cls}" aria-hidden="true">{extra}{inner}</div>'


def stamp(lines):
    return '<span class="stamp">' + "<br>".join(esc(x) for x in lines) + "</span>"


