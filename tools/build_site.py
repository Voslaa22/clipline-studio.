def process_svg():
    """Five-stage workflow with an animated beam between stages (port of Magic UI's AnimatedBeam:
    a short gradient travelling along the connector, easeOutExpo, repeating). Hidden under 700px; the cards say the same."""
    nodes = [("Long-form video", "ANY LONG UPLOAD", -1), ("Moment selection", "SCANNED · SCORED", .6),
             ("Vertical reframe", "9:16 · FACE IN FRAME", -.5), ("Captions & hooks", "WORD BY WORD", .7),
             ("Scheduled posting", "TIKTOK · REELS · SHORTS", -.8)]
    w, gap, x0, y = 160, 40, 6, 70
    out, beams, defs = [], [], []
    for i, (t, m, r) in enumerate(nodes):
        x = x0 + i * (w + gap)
        ac = " ac" if i in (1, 2, 3) else ""
        out.append(f'<g transform="rotate({r} {x + w / 2:.0f} {y + 40})"><rect class="n{ac}" x="{x}" y="{y}" width="{w}" height="80" rx="9"/>'
                   f'<text class="t" x="{x + w / 2:.0f}" y="{y + 34}" text-anchor="middle" font-size="20">{esc(t)}</text>'
                   f'<text class="m" x="{x + w / 2:.0f}" y="{y + 60}" text-anchor="middle" font-size="9">{esc(m)}</text></g>')
        if i < len(nodes) - 1:
            a, b2 = x + w + 2, x + w + gap - 2
            d = f"M{a} {y + 40}c6 -4 10 4 {b2 - a} 0"
            out.append(f'<path class="ar{" ac" if i in (0, 1, 2) else ""}" d="{d}"/>')
            defs.append(f'<linearGradient id="bm{i}" gradientUnits="userSpaceOnUse" x1="{a}" x2="{a}" y1="0" y2="0">'
                        f'<stop offset="0" stop-color="var(--accent)" stop-opacity="0"/><stop offset=".5" stop-color="var(--mark)"/><stop offset="1" stop-color="var(--accent)" stop-opacity="0"/>'
                        f'<animate attributeName="x1" values="{a - 30};{b2 + 10}" dur="5s" begin="{i * .5}s" repeatCount="indefinite" calcMode="spline" keySplines=".16 1 .3 1"/>'
                        f'<animate attributeName="x2" values="{a};{b2 + 40}" dur="5s" begin="{i * .5}s" repeatCount="indefinite" calcMode="spline" keySplines=".16 1 .3 1"/></linearGradient>')
            beams.append(f'<path class="bm" d="{d}" stroke="url(#bm{i})"/>')
    return (f'<svg viewBox="0 0 970 230" role="img" aria-label="Diagram: a long-form video goes through moment selection, vertical reframing and captions with hooks, then is scheduled and posted to TikTok, Reels and Shorts.">'
            f'<defs>{"".join(defs)}</defs>{"".join(out)}{"".join(beams)}'
            f'<text class="h" x="{x0 + 4}" y="190" text-anchor="start">every new upload</text>'
            f'<text class="h ac" x="{x0 + 2 * (w + gap) + w / 2:.0f}" y="190" text-anchor="middle">the part that takes judgment</text>'
            f'<text class="h" x="{x0 + 4 * (w + gap) + w - 4}" y="190" text-anchor="end">or as files, if you post yourself</text>'
            f'</svg>')


